import { expect, test } from "@playwright/test"

test("deshace y rehace una decisión", async ({ page }) => {
  await page.goto("/")
  await expect(page.getByText("Pendientes: 5.")).toBeVisible()
  const fila = page.getByRole("row", { name: /\bLC-110\b/ })
  await fila.getByLabel("Decisión").selectOption({ label: "Conservar B" })
  await fila.getByLabel("Motivo").fill("Conteo de tienda.")
  await fila.getByRole("button", { name: "Guardar decisión" }).click()
  await expect(page.getByText("Pendientes: 4.")).toBeVisible()
  await page.getByRole("button", { name: "Deshacer" }).click()
  await expect(page.getByText("Pendientes: 5.")).toBeVisible()
  await page.getByRole("button", { name: "Rehacer" }).click()
  await expect(page.getByText("Pendientes: 4.")).toBeVisible()
})

test("la paleta se abre con el teclado y se cierra con escape", async ({ page }) => {
  await page.goto("/")
  await expect(page.getByText("Pendientes: 5.")).toBeVisible()
  await page.keyboard.press("Control+k")
  const dialogo = page.getByRole("dialog", { name: "Comandos" })
  await expect(dialogo).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(dialogo).toBeHidden()
})

test("el borrador local se restaura y se puede borrar", async ({ page }) => {
  await page.goto("/")
  await expect(page.getByText("Pendientes: 5.")).toBeVisible()
  await page.getByRole("switch", { name: "Guardar borrador en este navegador" }).click()
  await expect(page.getByText("No lo actives en un ordenador compartido.")).toBeVisible()
  const fila = page.getByRole("row", { name: /\bLC-170\b/ })
  await fila.getByLabel("Decisión").selectOption({ label: "Conservar B" })
  await fila.getByLabel("Motivo").fill("Alta de tienda.")
  await fila.getByRole("button", { name: "Guardar decisión" }).click()
  await expect(page.getByText("Pendientes: 4.")).toBeVisible()
  await page.reload()
  await expect(page.getByText("Borrador local restaurado")).toBeVisible()
  await expect(page.getByRole("row", { name: /\bLC-170\b/ }).getByLabel("Motivo")).toHaveValue("Alta de tienda.")
  await page.getByRole("button", { name: "Borrar datos guardados" }).click()
  await page.getByRole("dialog", { name: "¿Borrar los datos guardados?" }).getByRole("button", { name: "Borrar" }).click()
  await expect(page.getByText("Datos borrados de este navegador.")).toBeVisible()
  await page.reload()
  await expect(page.getByText("Pendientes: 5.")).toBeVisible()
  await expect(page.getByText("Borrador local restaurado")).toHaveCount(0)
})
